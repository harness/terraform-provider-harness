func resourceSSOSAMLRead(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	c, ctx := meta.(*internal.Session).GetPlatformClientWithContext(ctx)

	resp, httpResp, err := c.AuthenticationSettingsApi.GetAuthenticationSettingsV2(ctx, c.AccountId)
	if err != nil {
		return helpers.HandleReadApiError(err, d, httpResp)
	}

	// For the data source the ID is not set yet; look up by the identifier argument.
	identifier := d.Id()
	if identifier == "" {
		identifier = d.Get("identifier").(string)
	}

	settings := findSAMLSettings(resp.Resource, identifier)
	if settings == nil {
		d.SetId("")
		return nil
	}

	readSSOSAML(d, settings)

	return nil
}

func resourceSSOSAMLCreate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	c, ctx := meta.(*internal.Session).GetPlatformClientWithContext(ctx)

	if d.Get("metadata_xml").(string) == "" {
		return diag.Errorf("metadata_xml is required when creating a SAML SSO configuration")
	}

	req := buildSAMLSettingsRequest(d)

	resp, httpResp, err := c.AuthenticationSettingsApi.CreateSamlSettings(ctx, c.AccountId, []byte(d.Get("metadata_xml").(string)), req)
	if err != nil {
		return helpers.HandleApiError(err, d, httpResp)
	}

	if resp.Resource == nil || resp.Resource.Uuid == "" {
		return diag.Errorf("SAML SSO configuration was created but the API returned no identifier")
	}

	d.SetId(resp.Resource.Uuid)
	d.Set("identifier", resp.Resource.Uuid)

	// The create API does not honor authentication_enabled: SamlSettings is always
	// persisted with authenticationEnabled=false on upload (the field is only ever
	// written by the dedicated enable/disable endpoint), regardless of the
	// PL_ENABLE_MULTIPLE_IDP_SUPPORT feature flag. So read the configuration back
	// and reconcile the flag through that endpoint when it differs from the
	// desired value. This mirrors the UI, which also enables login via a separate
	// call after uploading a SAML configuration.
	desiredAuthenticationEnabled := d.Get("authentication_enabled").(bool)
	if diags := resourceSSOSAMLRead(ctx, d, meta); diags != nil {
		return diags
	}
	if d.Id() == "" {
		return diag.Errorf("SAML SSO configuration not found after create")
	}
	if d.Get("authentication_enabled").(bool) != desiredAuthenticationEnabled {
		if diags := setSAMLAuthenticationEnabled(ctx, c, d.Id(), desiredAuthenticationEnabled); diags != nil {
			return diags
		}
	}

	return resourceSSOSAMLRead(ctx, d, meta)
}

func resourceSSOSAMLUpdate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	c, ctx := meta.(*internal.Session).GetPlatformClientWithContext(ctx)

	if d.HasChanges(
		"display_name", "friendly_saml_name", "metadata_xml", "entity_identifier",
		"logout_url", "group_membership_attr", "saml_provider_type",
		"client_id", "client_secret", "jit_enabled", "jit_validation_key", "jit_validation_value",
	) {
		req := buildSAMLSettingsRequest(d)

		_, httpResp, err := c.AuthenticationSettingsApi.UpdateSamlSettings(ctx, c.AccountId, d.Id(), []byte(d.Get("metadata_xml").(string)), req)
		if err != nil {
			return helpers.HandleApiError(err, d, httpResp)
		}
	}

	if d.HasChange("authentication_enabled") {
		if diags := setSAMLAuthenticationEnabled(ctx, c, d.Id(), d.Get("authentication_enabled").(bool)); diags != nil {
			return diags
		}
	}

	return resourceSSOSAMLRead(ctx, d, meta)
}

func resourceSSOSAMLDelete(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	c, ctx := meta.(*internal.Session).GetPlatformClientWithContext(ctx)

	_, httpResp, err := c.AuthenticationSettingsApi.DeleteSamlSettings(ctx, c.AccountId, d.Id())
	if err != nil {
		// The backend reports a missing SAML configuration with a 400
		// ("No Saml Metadata found ...") instead of a 404, so HandleApiError would
		// surface it as an error. Treat only that exact case as already deleted to
		// keep destroy idempotent; every other failure keeps its current behavior.
		if httpResp != nil && httpResp.StatusCode == http.StatusBadRequest &&
			strings.Contains(err.Error(), "No Saml Metadata found") {
			d.SetId("")
			return nil
		}
		return helpers.HandleApiError(err, d, httpResp)
	}

	d.SetId("")

	return nil
}

func setSAMLAuthenticationEnabled(ctx context.Context, c *nextgen.APIClient, samlSSOId string, enabled bool) diag.Diagnostics {
	resp, httpResp, err := c.AuthenticationSettingsApi.SetSamlAuthenticationEnabled(ctx, c.AccountId, samlSSOId, enabled)
	if err != nil {
		return helpers.HandleApiError(err, nil, httpResp)
	}

	if !resp.Resource {
		return diag.Errorf("failed to set SAML authentication enabled to %t", enabled)
	}

	return nil
}

// findSAMLSettings returns the SAML entry of the v2 authentication settings response
// matching the given identifier, or nil if there is none.
func findSAMLSettings(resp *nextgen.AuthenticationSettingsV2Response, identifier string) *nextgen.SamlSettings {
	if resp == nil {
		return nil
	}

	for i := range resp.NgAuthSettings {
		settings := &resp.NgAuthSettings[i]
		if settings.SettingsType == "SAML" && settings.Identifier == identifier {
			return settings
		}
	}

	return nil
}

func readSSOSAML(d *schema.ResourceData, settings *nextgen.SamlSettings) {
	d.SetId(settings.Identifier)
	d.Set("identifier", settings.Identifier)
	d.Set("display_name", settings.DisplayName)
	d.Set("friendly_saml_name", settings.FriendlySamlName)
	d.Set("entity_identifier", settings.EntityIdentifier)
	d.Set("origin", settings.Origin)
	d.Set("logout_url", settings.LogoutUrl)
	d.Set("group_membership_attr", settings.GroupMembershipAttr)
	d.Set("authorization_enabled", settings.AuthorizationEnabled)
	d.Set("authentication_enabled", settings.AuthenticationEnabled)
	d.Set("saml_provider_type", settings.SamlProviderType)
	d.Set("client_id", settings.ClientId)
	d.Set("jit_enabled", settings.JitEnabled)
	d.Set("jit_validation_key", settings.JitValidationKey)
	d.Set("jit_validation_value", settings.JitValidationValue)
	// metadata_xml and client_secret are not returned by the API; their configured
	// values are kept in state as-is.
}

// samlClientSecretMask mirrors io.harness.expression.SecretString.SECRET_MASK in
// harness-core. On update, when the backend receives this value as the client secret
// together with a non-empty clientId, it keeps the secret already stored for the
// SAML configuration (the same behavior as editing the config from the Harness UI).
const samlClientSecretMask = "**************"

func buildSAMLSettingsRequest(d *schema.ResourceData) *nextgen.SamlSettingsRequest {
	authorizationEnabled := d.Get("group_membership_attr").(string) != ""
	jitEnabled := d.Get("jit_enabled").(bool)

	// client_secret is never returned by the read API, so after an import (or any
	// out-of-band change) the state can hold a client_id without the secret. The
	// backend rejects clientId-without-clientSecret, so send the mask in that case,
	// which tells the backend to keep the stored secret - exactly what the UI sends
	// when a user edits the configuration without re-entering the secret.
	clientSecret := d.Get("client_secret").(string)
	if clientSecret == "" && d.Get("client_id").(string) != "" {
		clientSecret = samlClientSecretMask
	}

	return &nextgen.SamlSettingsRequest{
		DisplayName:          d.Get("display_name").(string),
		GroupMembershipAttr:  d.Get("group_membership_attr").(string),
		AuthorizationEnabled: &authorizationEnabled,
		LogoutUrl:            d.Get("logout_url").(string),
		EntityIdentifier:     d.Get("entity_identifier").(string),
		SamlProviderType:     d.Get("saml_provider_type").(string),
		ClientId:             d.Get("client_id").(string),
		ClientSecret:         clientSecret,
		FriendlySamlName:     d.Get("friendly_saml_name").(string),
		JitEnabled:           &jitEnabled,
		JitValidationKey:     d.Get("jit_validation_key").(string),
		JitValidationValue:   d.Get("jit_validation_value").(string),
	}
}
