// ResourceSSOSAML manages a SAML SSO configuration of a Harness account.
// Multiple SAML configurations are supported per account; the resource ID is the
// backend-generated SAML SSO identifier (samlSSOId).
//
// Note: the read API does not return the SAML metadata XML or the Azure client
// secret; their values are kept from the Terraform configuration, and out-of-band
// changes to them are not detected by terraform plan.
